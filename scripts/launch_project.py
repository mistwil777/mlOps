"""Deploy a client bundle as a Docker stack on a target machine.

This script is for DELIVERING a bundle to a client or to the on-premise
MLOps server. It is NOT used during fine-tuning (MLX runs directly on
the host, without Docker).

Bundle contents (generated by scripts/export_bundle.py):
  bundles/<project_id>/
    docker-compose.yml
    .env
    adapters/           — LoRA adapters (Capgemini IP)
    qdrant-snapshot/    — pre-loaded RAG vectors

The client runs:  docker compose up -d
Three services start:
  ollama   — inference, loads base model + adapters dynamically
  qdrant   — vector store, pre-loaded with project RAG data
  router   — HTTP orchestrator, routes requests to the right adapter(s)

isolation_level (from project config):
  standard    — bridge network (LAN accessible)
  sovereign   — internal bridge, no external network (confidentiel / secret)
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import yaml

_TEMPLATE_DIR  = Path("infra/docker/project-template")
_BUNDLES_DIR   = Path("bundles")

# Port allocation — projects get sequential blocks of 10 ports
_PORT_BASE  = 9000
_BLOCK_SIZE = 10  # ollama=+0, qdrant=+1, router=+2


def _next_port_block() -> int:
    """Find the first unused port block by scanning existing bundle .env files."""
    used = set()
    for env_file in _BUNDLES_DIR.glob("*/.env"):
        for line in env_file.read_text().splitlines():
            if line.startswith("OLLAMA_PORT="):
                try:
                    base = int(line.split("=")[1])
                    used.add((base - _PORT_BASE) // _BLOCK_SIZE)
                except ValueError:
                    pass
    block = 0
    while block in used:
        block += 1
    return _PORT_BASE + block * _BLOCK_SIZE


def launch(project: str, force: bool = False) -> Path:
    cfg_path = Path("config/projects") / f"{project}.yaml"
    if not cfg_path.exists():
        raise FileNotFoundError(f"Project config not found: {cfg_path}")

    cfg          = yaml.safe_load(cfg_path.read_text())
    isolation    = cfg.get("isolation_level", "standard")
    classification = cfg.get("classification", "interne")

    if classification in ("confidentiel", "secret") and isolation != "sovereign":
        print(f"WARNING: classification={classification} — forcing isolation_level=sovereign")
        isolation = "sovereign"

    bundle_dir = _BUNDLES_DIR / project
    if bundle_dir.exists():
        if not force:
            raise FileExistsError(
                f"Bundle already deployed: {bundle_dir}\n"
                "Use --force to redeploy (stops the existing stack first)."
            )
        print(f"  Stopping existing stack for {project}…")
        subprocess.run(["docker", "compose", "down"], cwd=bundle_dir, check=False)
        shutil.rmtree(bundle_dir)

    bundle_dir.mkdir(parents=True)
    shutil.copy(_TEMPLATE_DIR / "docker-compose.yml", bundle_dir / "docker-compose.yml")

    # Adapters and Qdrant snapshot must exist (produced by scripts/export_bundle.py)
    adapters_src = Path("exports") / project / "adapters"
    qdrant_src   = Path("exports") / project / "qdrant-snapshot"
    if not adapters_src.exists():
        raise FileNotFoundError(f"Adapters not found: {adapters_src} — run export_bundle.py first")
    if not qdrant_src.exists():
        raise FileNotFoundError(f"Qdrant snapshot not found: {qdrant_src} — run export_bundle.py first")

    # Copy adapters and Qdrant snapshot into bundle
    shutil.copytree(adapters_src, bundle_dir / "adapters")
    shutil.copytree(qdrant_src,   bundle_dir / "qdrant-snapshot")

    port_base = _next_port_block()
    repo_root = Path(".").resolve()

    env_vars = {
        "PROJECT_NAME":         project,
        "OLLAMA_PORT":          str(port_base),
        "QDRANT_PORT":          str(port_base + 1),
        "ROUTER_PORT":          str(port_base + 2),
        "MODELS_PATH":          str(repo_root / "models" / "base"),
        "ADAPTERS_PATH":        str(bundle_dir / "adapters"),
        "QDRANT_SNAPSHOT_PATH": str(bundle_dir / "qdrant-snapshot"),
        "INTERNAL_NETWORK":     "true" if isolation == "sovereign" else "false",
    }

    (bundle_dir / ".env").write_text("\n".join(f"{k}={v}" for k, v in env_vars.items()))

    print(f"Launching client bundle: {project} (isolation={isolation})")
    print(f"  Ollama  (inference) : http://localhost:{port_base}")
    print(f"  Qdrant  (vectors)   : http://localhost:{port_base + 1}")
    print(f"  Router  (API)       : http://localhost:{port_base + 2}")
    print(f"  Bundle dir          : {bundle_dir}")
    if isolation == "sovereign":
        print("  Network             : INTERNAL (no external access)")

    result = subprocess.run(
        ["docker", "compose", "up", "-d", "--pull", "missing"],
        cwd=bundle_dir,
        check=False,
    )
    if result.returncode != 0:
        print("ERROR: docker compose up failed")
        sys.exit(1)

    cfg["bundle"] = {
        "dir":   str(bundle_dir),
        "ports": {"ollama": port_base, "qdrant": port_base + 1, "router": port_base + 2},
        "isolation": isolation,
    }
    cfg_path.write_text(yaml.dump(cfg, default_flow_style=False, allow_unicode=True))
    return bundle_dir


def stop(project: str, remove: bool = False) -> None:
    bundle_dir = _BUNDLES_DIR / project
    if not bundle_dir.exists():
        print(f"No bundle deployed for project '{project}'")
        return
    cmd = ["docker", "compose", "down"]
    if remove:
        cmd += ["-v", "--remove-orphans"]
    subprocess.run(cmd, cwd=bundle_dir, check=True)
    if remove:
        shutil.rmtree(bundle_dir)
        print(f"Bundle removed: {bundle_dir}")
    else:
        print(f"Stack stopped (bundle dir kept): {bundle_dir}")


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="Deploy or stop a client bundle Docker stack")
    sub = parser.add_subparsers(dest="cmd")

    up = sub.add_parser("up", help="Deploy a client bundle")
    up.add_argument("--project", required=True)
    up.add_argument("--force", action="store_true", help="Redeploy if already running")

    down = sub.add_parser("down", help="Stop a deployed bundle")
    down.add_argument("--project", required=True)
    down.add_argument("--remove", action="store_true", help="Also remove bundle dir + volumes")

    args = parser.parse_args()

    if args.cmd == "up":
        launch(args.project, force=args.force)
    elif args.cmd == "down":
        stop(args.project, remove=args.remove)
    else:
        parser.print_help()
        sys.exit(1)


if __name__ == "__main__":
    main()
